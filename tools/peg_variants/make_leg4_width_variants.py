"""Body-width variants of the screwing peg (furniture_bench square_table_leg4, sdf_hybrid).

The peg is a 25 mm thread (x in [-43.75, -18.75] mm, SDF collision) under a hollow square body
(x in [-18.75, 43.75] mm, 30 x 30 mm cross-section, 12 CoACD hulls). A variant scales only the
body's cross-section (y and z about the long axis) to W mm; its length and the thread mesh are
unchanged, so the thread still fits the hole and the shoulder stays at x = -18.75 mm.

Per width it writes assets/urdf/furniture_bench/square_table/square_table_leg4/width_variants/w<W*10>/:
    square_table_leg4_body.obj   the scaled body (visual reference)
    body_coacd/decomp_<i>.obj    CoACD hulls of the scaled body (threshold 0.05, max 12 hulls, like the original 12)
    square_table_leg4_matchedmass_sdf_hybrid.urdf
        thread = ../../sdf_hybrid/square_table_leg4_thread.obj (shared, SDF 256), body = the new hulls,
        mass 22.75 g like the original; COM and inertia = the original's, corrected by how a uniform-density
        solid model (cylinder thread + box body, see model_props) changes with the width.
The 30 mm entry points at the original sdf_hybrid URDF (nothing regenerated).

Needs coacd (not in the Isaac venv): pip install --target <dir> coacd, then PYTHONPATH=<dir>.
Usage: python tools/peg_variants/make_leg4_width_variants.py [--widths 25 27.5 32.5 35]
"""
import argparse
import json
from pathlib import Path

import numpy as np
import trimesh

ROOT = Path(__file__).resolve().parents[2]
LEG = ROOT / "assets/urdf/furniture_bench/square_table/square_table_leg4"
SRC = LEG / "sdf_hybrid"
OUT = LEG / "width_variants"
W0_MM = 30.0
MASS = 0.022750
# Original matched-mass inertial (square_table_leg4_matchedmass_sdf_hybrid.urdf).
COM0 = np.array([0.005745, 0.0, -0.000001])
I0 = np.array([[2.570880e-06, -2.009384e-10, -8.317314e-09],
               [-2.009384e-10, 1.202610e-05, -2.897770e-12],
               [-8.317314e-09, -2.897770e-12, 1.202563e-05]])


def variant_dir(w_mm: float) -> Path:
    return OUT / f"w{int(round(w_mm * 10))}"


def scale_yz(v: np.ndarray, s: float) -> np.ndarray:
    v = np.array(v, dtype=float)
    v[:, 1:] *= s
    return v


def model_props(w):
    """Unit-mass, uniform-density solid model of a peg with a w x w body: thread = solid cylinder (r 11 mm, the mean
    of the thread's 12.2 mm major and ~9.8 mm minor radius), x in [-43.75, -18.75] mm; body = solid box, x in
    [-18.75, 43.75] mm. At 30 mm it gives COM x 6.2 mm, Ixx 3.1e-6 / Iyy 1.3e-5 kg m^2 at 22.75 g vs the original
    URDF's 5.7 mm, 2.6e-6 / 1.2e-5, so the original was a solid body too. Returns COM and inertia about the COM."""
    r, xt0, xt1, xb0, xb1 = 0.011, -0.04375, -0.01875, -0.01875, 0.04375
    vt, vb = np.pi * r * r * (xt1 - xt0), w * w * (xb1 - xb0)
    mt, mb = vt / (vt + vb), vb / (vt + vb)
    ct, cb = np.array([(xt0 + xt1) / 2, 0, 0]), np.array([(xb0 + xb1) / 2, 0, 0])
    com = mt * ct + mb * cb
    Lt, Lb = xt1 - xt0, xb1 - xb0
    It = mt * np.diag([r * r / 2, (3 * r * r + Lt * Lt) / 12, (3 * r * r + Lt * Lt) / 12])
    Ib = mb * np.diag([(2 * w * w) / 12, (Lb * Lb + w * w) / 12, (Lb * Lb + w * w) / 12])
    par = lambda m, c: m * (np.dot(c - com, c - com) * np.eye(3) - np.outer(c - com, c - com))
    return com, It + par(mt, ct) + Ib + par(mb, cb)


def urdf(w_mm: float, n_hulls: int, com, inertia) -> str:
    rows = []
    for i in range(n_hulls):
        g = f'<geometry><mesh filename="body_coacd/decomp_{i}.obj" scale="1 1 1"/></geometry>'
        rows.append(f'    <visual><origin xyz="0 0 0" rpy="0 0 0"/>{g}<material name="body"/></visual>')
        rows.append(f'    <collision><origin xyz="0 0 0" rpy="0 0 0"/>{g}</collision>')
    I = inertia
    return f"""<?xml version="1.0" encoding="utf-8"?>
<robot name="square_table_leg4_w{int(round(w_mm * 10))}_sdf_hybrid_matchedmass">
  <!-- Body-width variant: body cross-section {w_mm:g} x {w_mm:g} mm (original 30), same length, same thread.
       Generated by tools/peg_variants/make_leg4_width_variants.py. -->
  <link name="base_link">
    <inertial>
      <mass value="{MASS:.6f}"/>
      <origin xyz="{com[0]:.6f} {com[1]:.6f} {com[2]:.6f}" rpy="0 0 0"/>
      <inertia ixx="{I[0, 0]:.6e}" ixy="{I[0, 1]:.6e}" ixz="{I[0, 2]:.6e}" iyy="{I[1, 1]:.6e}" iyz="{I[1, 2]:.6e}" izz="{I[2, 2]:.6e}"/>
    </inertial>
  </link>
  <material name="thread">
    <color rgba="0.95 0.55 0.10 1.0"/>
  </material>
  <material name="body">
    <color rgba="0.50 0.50 0.50 1.0"/>
  </material>
  <link name="thread_link">
    <visual>
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry><mesh filename="../../sdf_hybrid/square_table_leg4_thread.obj" scale="1 1 1"/></geometry>
      <material name="thread"/>
    </visual>
    <collision>
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry><mesh filename="../../sdf_hybrid/square_table_leg4_thread.obj" scale="1 1 1"/></geometry>
      <sdf resolution="256"/>
    </collision>
  </link>
  <joint name="base_to_thread" type="fixed">
    <parent link="base_link"/>
    <child link="thread_link"/>
    <origin xyz="0 0 0" rpy="0 0 0"/>
  </joint>
  <link name="body_link">
{chr(10).join(rows)}
  </link>
  <joint name="base_to_body" type="fixed">
    <parent link="base_link"/>
    <child link="body_link"/>
    <origin xyz="0 0 0" rpy="0 0 0"/>
  </joint>
</robot>
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--widths", type=float, nargs="+", default=[25.0, 27.5, 32.5, 35.0])
    ap.add_argument("--threshold", type=float, default=0.05)
    ap.add_argument("--max-hulls", type=int, default=12)
    a = ap.parse_args()
    import coacd

    coacd.set_log_level("error")
    body = trimesh.load(SRC / "square_table_leg4_body.obj", force="mesh", process=False)
    com_m0, I_m0 = model_props(W0_MM / 1000.0)
    print(f"model at 30 mm: com {com_m0.round(6)} diag {np.diag(I_m0 * MASS)} | urdf com {COM0} diag {np.diag(I0)}")
    info = {}
    for w in a.widths:
        s = w / W0_MM
        d = variant_dir(w)
        (d / "body_coacd").mkdir(parents=True, exist_ok=True)
        bw = trimesh.Trimesh(scale_yz(body.vertices, s), body.faces, process=False)
        bw.export(d / "square_table_leg4_body.obj")
        parts = coacd.run_coacd(coacd.Mesh(bw.vertices, bw.faces), threshold=a.threshold,
                                max_convex_hull=a.max_hulls)
        hulls = []
        for i, (v, f) in enumerate(parts):
            h = trimesh.Trimesh(v, f, process=True)
            h.export(d / "body_coacd" / f"decomp_{i}.obj")
            hulls.append(h)
        com_m, I_m = model_props(w / 1000.0)
        com = COM0.copy()
        com[0] += com_m[0] - com_m0[0]  # the body is symmetric about the long axis: keep y, z of the original
        ratio = np.where(np.abs(I_m0) > 1e-12, I_m / np.where(np.abs(I_m0) > 1e-12, I_m0, 1.0), 1.0)
        inertia = np.diag(np.diag(I0) * np.diag(ratio))  # off-diagonals of the original are ~1e-4 of the diagonal
        (d / "square_table_leg4_matchedmass_sdf_hybrid.urdf").write_text(urdf(w, len(hulls), com, inertia))
        lo = np.min([h.bounds[0] for h in hulls], 0)
        hi = np.max([h.bounds[1] for h in hulls], 0)
        info[w] = {"hulls": len(hulls), "hull_bounds_mm": [(lo * 1e3).round(3).tolist(), (hi * 1e3).round(3).tolist()],
                   "com": com.tolist(), "inertia_diag": np.diag(inertia).tolist()}
        print(w, info[w], flush=True)
    (OUT / "variants.json").write_text(json.dumps(info, indent=1))


if __name__ == "__main__":
    main()
