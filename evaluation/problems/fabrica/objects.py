import json
from pathlib import Path

from evaluation.objects import Object, rescale_by_factor, NAME_TO_OBJECT

from evaluation.objects import get_repo_root_dir

ASSETS_DIR = get_repo_root_dir() / "assets" / "urdf" / "fabrica"

def _discover_assemblies():
    """Return all subdirs of ASSETS_DIR that contain canonical_transforms.json.

    Picks up not just the canonical assembly names (beam, car, …) but also
    user-generated scaled clones (e.g. beam_2x produced by scale_assembly.py).
    """
    return sorted(
        d.name
        for d in ASSETS_DIR.iterdir()
        if d.is_dir() and (d / "canonical_transforms.json").exists()
    )


ALL_ASSEMBLIES = _discover_assemblies()

def _load_assembly_objects(assembly_name):
    """Load Object entries using canonical extents from canonical_transforms.json.

    URDFs are expected to already exist (generated by compute_canonical.py
    and run_coacd.py). This function only reads, never writes.
    """
    transforms_path = ASSETS_DIR / assembly_name / "canonical_transforms.json"
    if not transforms_path.exists():
        return {}

    with open(transforms_path) as f:
        transforms = json.load(f)

    objects = {}
    for pid, data in transforms.items():
        name = f"{assembly_name}_{pid}"
        part_dir = ASSETS_DIR / assembly_name / pid
        ext = data["canonical_extents"]
        scale = rescale_by_factor(tuple(ext), factor=25)

        # Base variant (V-HACD collision)
        urdf_path = part_dir / f"{name}.urdf"
        if urdf_path.exists():
            objects[name] = Object(urdf_path=urdf_path, scale=scale, need_vhacd=True)

        # SDF variant
        sdf_urdf_path = part_dir / f"{name}_sdf.urdf"
        if sdf_urdf_path.exists():
            objects[f"{name}_sdf"] = Object(urdf_path=sdf_urdf_path, scale=scale, need_vhacd=False)

        # CoACD variant (generated by run_coacd.py)
        coacd_urdf_path = part_dir / "coacd" / f"{name}_coacd.urdf"
        if coacd_urdf_path.exists():
            objects[f"{name}_coacd"] = Object(urdf_path=coacd_urdf_path, scale=scale, need_vhacd=False)

        # Physically-matched-mass siblings (same geometry as base/CoACD,
        # explicit <mass>+<inertia> blocks derived from measured part mass
        # because Isaac Sim silently ignores URDF <density> tags).
        matched_urdf_path = part_dir / f"{name}_matchedmass.urdf"
        if matched_urdf_path.exists():
            objects[f"{name}_matchedmass"] = Object(
                urdf_path=matched_urdf_path, scale=scale, need_vhacd=True,
            )
        matched_coacd_path = part_dir / "coacd" / f"{name}_matchedmass_coacd.urdf"
        if matched_coacd_path.exists():
            objects[f"{name}_matchedmass_coacd"] = Object(
                urdf_path=matched_coacd_path, scale=scale, need_vhacd=False,
            )
        matched_sdf_hybrid_path = part_dir / "sdf_hybrid" / f"{name}_matchedmass_sdf_hybrid.urdf"
        if matched_sdf_hybrid_path.exists():
            objects[f"{name}_matchedmass_sdf_hybrid"] = Object(
                urdf_path=matched_sdf_hybrid_path, scale=scale, need_vhacd=False,
            )

        # SDF + CoACD hybrid variant (generated by step2_generate_sdf_hybrid.py).
        # need_vhacd=False is critical — V-HACD on the multi-link URDF would
        # re-decompose the SDF mesh and the body CoACD hulls, breaking both.
        sdf_hybrid_urdf = part_dir / "sdf_hybrid" / f"{name}_sdf_hybrid.urdf"
        if sdf_hybrid_urdf.exists():
            objects[f"{name}_sdf_hybrid"] = Object(
                urdf_path=sdf_hybrid_urdf, scale=scale, need_vhacd=False,
            )

    return objects


FABRICA_NAME_TO_OBJECT = {}
for _assembly in ALL_ASSEMBLIES:
    FABRICA_NAME_TO_OBJECT.update(_load_assembly_objects(_assembly))

# Register into the global object registry so the sim can find them
NAME_TO_OBJECT.update(FABRICA_NAME_TO_OBJECT)
