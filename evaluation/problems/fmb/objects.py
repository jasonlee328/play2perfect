"""FMB (Functional Manipulation Benchmark) shaped pegs for straight insertion.

Assets under ``assets/urdf/fmb_insertion/<shape>/`` are generated by FoundationTouch
``tools/fmb_insertion/make_fmb_insertion_assets.py`` (meta in ``assets/urdf/fmb_insertion/meta.json``):
one FMB cross-section per family, scaled uniformly to a 30 mm max cross-section dimension, extruded to
150 mm along the peg's +x (the L-peg's frame), 57.8 g (= lpeg_matchedmass), collision = exact convex prisms.
"""

import json

from evaluation.objects import NAME_TO_OBJECT, Object, get_repo_root_dir

ASSETS_DIR = get_repo_root_dir() / "assets" / "urdf" / "fmb_insertion"
FMB_SHAPES = ("ellipse", "star", "arch", "hexagon", "rrect", "circle")


def _register() -> None:
    meta_path = ASSETS_DIR / "meta.json"
    if not meta_path.is_file():
        return
    meta = json.loads(meta_path.read_text())
    for shape in FMB_SHAPES:
        urdf = ASSETS_DIR / shape / "peg" / f"fmb_{shape}_peg.urdf"
        if shape not in meta or not urdf.is_file():
            continue
        # Policy-facing grasp-box scale = metric bbox / object_base_size (0.04 m), like the L-peg's 25x.
        NAME_TO_OBJECT[f"fmb_{shape}_peg"] = Object(
            urdf_path=urdf, scale=tuple(float(v) for v in meta[shape]["object_scale"]), need_vhacd=False,
        )


_register()
