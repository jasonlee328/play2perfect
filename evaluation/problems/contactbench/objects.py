"""ContactBench 1.0 (jingyi-xiang.github.io/contactbench) printable parts as PreciseAssembly objects.

Assets under ``assets/urdf/contactbench/`` are generated by FoundationTouch
``tools/contactbench/make_contactbench_assets.py`` from the site's printing STLs (meta in
``assets/urdf/contactbench/meta.json``): SDF collision of the mesh, origin at the centre of mass, mass from the
volume at 620 kg/m^3 (PLA at about 50% fill).
"""

import json

from evaluation.objects import NAME_TO_OBJECT, Object, get_repo_root_dir

ASSETS_DIR = get_repo_root_dir() / "assets" / "urdf" / "contactbench"


def _register() -> None:
    meta_path = ASSETS_DIR / "meta.json"
    if not meta_path.is_file():
        return
    meta = json.loads(meta_path.read_text())
    for name, m in meta["objects"].items():
        urdf = ASSETS_DIR / "objects" / name / f"{name}.urdf"
        if urdf.is_file():
            NAME_TO_OBJECT[f"cb_{name}"] = Object(
                urdf_path=urdf, scale=tuple(float(v) for v in m["object_scale"]), need_vhacd=False,
            )


_register()
